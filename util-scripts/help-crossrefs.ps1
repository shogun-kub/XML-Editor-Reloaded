# Builds help/REFERENCE-MAP.md from cross-document links in the table help documents.
# The map is generated: edit the source documents, then run this script with -Write.
# -Check verifies that the committed map matches the current documents.

[CmdletBinding()]
param(
    [switch]$Write,
    [switch]$Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$helpRoot = Join-Path $repoRoot 'xml-editor-reloaded/help'
$tablesRoot = Join-Path $helpRoot 'tables'
$outputPath = Join-Path $helpRoot 'REFERENCE-MAP.md'

if (-not (Test-Path -LiteralPath $tablesRoot)) {
    throw "Table help root not found: $tablesRoot"
}

. (Join-Path $PSScriptRoot 'help-common.ps1')

$helpRootFull = (Resolve-Path -LiteralPath $helpRoot).Path
$records = [System.Collections.Generic.List[object]]::new()

foreach ($file in Get-ChildItem -LiteralPath $tablesRoot -Recurse -File -Filter *.md | Sort-Object FullName) {
    $sourcePath = [System.IO.Path]::GetRelativePath($helpRootFull, $file.FullName).Replace('\', '/')
    $lines = Get-Content -LiteralPath $file.FullName
    $currentField = $null
    $currentContext = 'Document'

    for ($i = 0; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]

        if ($line -match '^##\s+(.+?)\s*$') {
            $section = $matches[1].Trim()
            $currentField = $null
            $currentContext = if ($section -eq 'Relations') { 'Relations' } else { 'Document' }
        }
        elseif ($line -match '^###\s+`([^`]+)`') {
            $currentField = $matches[1]
            $currentContext = 'Field'
        }
        elseif ($line -match '^###\s+') {
            $currentField = $null
            $currentContext = 'Document'
        }

        if ($line -match '^- \*\*(Description|Values|Default|Source|Numeric semantics|Only used with):\*\*') {
            $currentContext = $matches[1]
        }

        foreach ($link in [regex]::Matches($line, '\[([^\]]*)\]\(([^)]+)\)')) {
            $rawTarget = $link.Groups[2].Value.Trim()
            if ($rawTarget -match '^(https?:|mailto:|#)') {
                continue
            }
            if ($rawTarget -notmatch '\.md(?:#|$)') {
                continue
            }

            $parts = $rawTarget -split '#', 2
            $relativeTarget = $parts[0]
            $anchor = if ($parts.Count -gt 1) { $parts[1] } else { '' }
            $fullTarget = Join-Path $file.DirectoryName $relativeTarget
            if (-not (Test-Path -LiteralPath $fullTarget)) {
                continue
            }

            $fullTarget = (Resolve-Path -LiteralPath $fullTarget).Path
            if ($fullTarget -eq $file.FullName) {
                continue
            }
            if (-not $fullTarget.StartsWith($helpRootFull, [System.StringComparison]::OrdinalIgnoreCase)) {
                continue
            }

            $targetPath = [System.IO.Path]::GetRelativePath($helpRootFull, $fullTarget).Replace('\', '/')
            $context = if ($currentField) { $currentContext } else { $currentContext }
            $field = if ($currentField) { $currentField } else { '' }
            $record = [pscustomobject]@{
                SourcePath = $sourcePath
                SourceFile = $file.FullName
                Field = $field
                FieldAnchor = if ($field) { ConvertTo-HelpAnchor $field } else { '' }
                TargetPath = $targetPath
                TargetAnchor = $anchor
                Context = $context
            }

            $key = '{0}|{1}|{2}|{3}|{4}' -f $record.SourcePath, $record.Field, $record.TargetPath, $record.TargetAnchor, $record.Context
            if (-not $records.Where({ $_.Key -eq $key }).Count) {
                $record | Add-Member -NotePropertyName Key -NotePropertyValue $key
                $records.Add($record)
            }
        }
    }
}

$records = @($records | Sort-Object SourcePath, Field, TargetPath, TargetAnchor, Context)

function Get-TargetLabel {
    param([string]$TargetPath, [string]$Anchor)

    $label = if ($TargetPath -like 'tables/*') {
        $TargetPath.Substring(7) -replace '\.md$', ''
    } else {
        [System.IO.Path]::GetFileName($TargetPath) -replace '\.md$', ''
    }
    return $label
}

function Get-Domain {
    param([string]$SourcePath)

    if ($SourcePath -match '^tables/([^/]+)/') {
        return $matches[1]
    }
    return 'General'
}

$groups = $records | Group-Object { Get-Domain $_.SourcePath } | Sort-Object Name
$sourceDocs = @($records | Select-Object -ExpandProperty SourcePath -Unique)
$targetDocs = @($records | Select-Object -ExpandProperty TargetPath -Unique)

$out = [System.Collections.Generic.List[string]]::new()
$out.Add('<!-- Generated by util-scripts/help-crossrefs.ps1. Do not edit by hand. -->')
$out.Add('')
$out.Add('# Cross-reference map')
$out.Add('')
$out.Add('This map lists cross-document links from the table help documents. It is the quick')
$out.Add('reference for "which document explains the target of this field". The links in the')
$out.Add('table documents remain the source of truth; this page is derived from them.')
$out.Add('')
$out.Add("Source documents with links: **$($sourceDocs.Count)** of 94. Distinct links: **$($records.Count)**.")
$out.Add('')
$out.Add('## How to update')
$out.Add('')
$out.Add('```sh')
$out.Add('pwsh -NoProfile -ExecutionPolicy Bypass -File util-scripts/help-crossrefs.ps1 -Write')
$out.Add('```')
$out.Add('')
$out.Add('`-Check` verifies that this file matches the current documents. Do not edit the map by')
$out.Add('hand: add or fix the link in the table document, then regenerate.')
$out.Add('')

foreach ($group in $groups) {
    $out.Add("## $($group.Name)")
    $out.Add('')
    foreach ($doc in ($group.Group | Group-Object SourcePath | Sort-Object Name)) {
        $sourcePath = $doc.Name
        $out.Add("### [$sourcePath]($sourcePath)")
        $out.Add('')
        $out.Add('| Source field | Target | Context |')
        $out.Add('|---|---|---|')
        foreach ($record in ($doc.Group | Sort-Object Field, TargetPath, TargetAnchor, Context)) {
            $sourceField = if ($record.Field) {
                $anchor = if ($record.FieldAnchor) { "#$($record.FieldAnchor)" } else { '' }
                "[``$($record.Field)``]($($record.SourcePath)$anchor)"
            } else {
                '—'
            }
            $targetAnchor = if ($record.TargetAnchor) { "#$($record.TargetAnchor)" } else { '' }
            $targetLabel = Get-TargetLabel $record.TargetPath $record.TargetAnchor
            $target = "[$targetLabel]($($record.TargetPath)$targetAnchor)"
            $out.Add("| $sourceField | $target | $($record.Context) |")
        }
        $out.Add('')
    }
}

$content = ($out -join "`n") + "`n"

if ($Check) {
    if (-not (Test-Path -LiteralPath $outputPath)) {
        Write-Error "REFERENCE-MAP.md is missing: $outputPath"
        exit 1
    }
    $existing = [System.IO.File]::ReadAllText($outputPath)
    if ($existing -ne $content) {
        Write-Error "REFERENCE-MAP.md is out of date. Run: util-scripts/help-crossrefs.ps1 -Write"
        exit 1
    }
    Write-Host "REFERENCE-MAP.md is up to date."
    exit 0
}

if ($Write) {
    [System.IO.File]::WriteAllText($outputPath, $content, [System.Text.UTF8Encoding]::new($false))
    Write-Host "Wrote $outputPath"
    exit 0
}

Write-Host "Source documents with links: $($sourceDocs.Count) of 94"
Write-Host "Distinct links: $($records.Count)"
Write-Host "Run with -Write to update REFERENCE-MAP.md, or -Check to verify it."
